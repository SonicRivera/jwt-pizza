import { test, expect } from './testSetup';
import { login, mockService } from './mockService';

test('profile edits persist through reload and login with new credentials', async ({ page }) => {
  const { calls, state } = await mockService(page);
  await page.goto('/login');
  await login(page);
  await page.getByRole('link', { name: 'KC', exact: true }).click();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Edit user' });
  await expect(dialog.getByLabel('Name', { exact: true })).toHaveValue('Kai Chen');
  await page.screenshot({ path: test.info().outputPath('edit-user.png'), fullPage: true });
  await dialog.getByLabel('Name', { exact: true }).fill("Kai O'Brien");
  await dialog.getByLabel('Email', { exact: true }).fill('updated@jwt.com');
  await dialog.getByLabel('Password', { exact: true }).fill('new-password');
  state.updateFails = true;
  await dialog.getByRole('button', { name: 'Update', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Update failed');
  await expect(page.getByRole('main')).toContainText('Kai Chen');
  state.updateFails = false;
  await dialog.getByRole('button', { name: 'Update', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByRole('main')).toContainText("Kai O'Brien");
  expect(calls.find(c => c.method === 'PUT' && c.path === '/api/user/3')?.body.password).toBe('new-password');
  expect(await page.evaluate(() => localStorage.getItem('token'))).toBe('updated-token');
  await page.reload();
  await expect(page.getByRole('main')).toContainText('updated@jwt.com');
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(dialog.getByLabel('Password', { exact: true })).toHaveValue('');
  await dialog.getByLabel('Name', { exact: true }).fill('Kai Updated');
  await dialog.getByRole('button', { name: 'Update', exact: true }).click();
  await expect(dialog).toBeHidden();
  expect(calls.filter(c => c.method === 'PUT' && c.path === '/api/user/3').slice(-1)[0]?.body).not.toHaveProperty('password');
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await dialog.getByLabel('Name', { exact: true }).fill('Discard this');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('main')).not.toContainText('Discard this');
  await page.getByRole('link', { name: 'Logout', exact: true }).click();
  await page.getByRole('link', { name: 'Login', exact: true }).click();
  await page.getByPlaceholder('Email address').fill('updated@jwt.com');
  await page.getByPlaceholder('Password').fill('new-password');
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await page.getByRole('link', { name: 'KU', exact: true }).click();
  await expect(page.getByRole('main')).toContainText('Kai Updated');
});

test('admin lists roles, paginates and filters users, and deletes with retry', async ({ page }) => {
  const { users, state, calls } = await mockService(page);
  for (let i = 4; i <= 11; i++) users.push({ id: String(i), name: `Pizza Diner ${i}`, email: `d${i}@jwt.com`, roles: [{ role: 'diner' }] });
  await page.goto('/login');
  await login(page, 'a@jwt.com');
  await page.getByRole('link', { name: 'Admin', exact: true }).click();
  const table = page.getByRole('table', { name: 'Users', exact: true });
  await expect(table).toContainText('Kai Chen');
  await expect(table).toContainText('d@jwt.com');
  await expect(table).toContainText('admin');
  await expect(table).toContainText('franchisee');
  await page.screenshot({ path: test.info().outputPath('admin-users.png'), fullPage: true });
  await expect(page.getByRole('button', { name: 'Previous users' })).toBeDisabled();
  await page.getByRole('button', { name: 'Next users' }).click();
  await expect(table).toContainText('Pizza Diner 11');
  await expect(page.getByRole('button', { name: 'Next users' })).toBeDisabled();
  await page.getByRole('button', { name: 'Previous users' }).click();
  await expect(table).toContainText('Kai Chen');
  await page.getByPlaceholder('Filter users').fill('Pizza Diner');
  await page.getByRole('button', { name: 'Filter users', exact: true }).click();
  await expect(table).not.toContainText('Kai Chen');
  await expect(table.locator('tbody tr')).toHaveCount(8);
  await page.getByPlaceholder('Filter users').fill('absent');
  await page.getByRole('button', { name: 'Filter users', exact: true }).click();
  await expect(table).toContainText('No users found');
  await page.getByPlaceholder('Filter users').fill('');
  await page.getByRole('button', { name: 'Filter users', exact: true }).click();
  const row = table.getByRole('row').filter({ hasText: 'Kai Chen' });
  await row.getByRole('button', { name: 'Delete' }).click();
  const dialog = page.getByRole('dialog', { name: 'Delete user' });
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  expect(calls.filter(c => c.method === 'DELETE' && c.path === '/api/user/3')).toHaveLength(0);
  await row.getByRole('button', { name: 'Delete' }).click();
  state.deleteFails = true;
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Delete failed');
  state.deleteFails = false;
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(table).not.toContainText('Kai Chen');
  await expect(page.getByRole('button', { name: 'Next users' })).toBeDisabled();
  await page.reload();
  await expect(table).not.toContainText('Kai Chen');
  await expect(table).toContainText('Mama Ricci');
});

test('deleting the only user on the last page returns to the previous page', async ({ page }) => {
  const { users } = await mockService(page);
  for (let i = 4; i <= 11; i++) users.push({ id: String(i), name: `Pizza Diner ${i}`, email: `d${i}@jwt.com`, roles: [{ role: 'diner' }] });
  await page.goto('/login');
  await login(page, 'a@jwt.com');
  await page.goto('/admin-dashboard');
  await page.getByRole('button', { name: 'Next users' }).click();
  await page.getByRole('row').filter({ hasText: 'Pizza Diner 11' }).getByRole('button', { name: 'Delete' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByRole('table', { name: 'Users', exact: true })).toContainText('Kai Chen');
  await expect(page.getByRole('button', { name: 'Previous users' })).toBeDisabled();
});

test('listing errors can be retried and an administrator can delete their own account', async ({ page }) => {
  const { state } = await mockService(page);
  state.listFails = true;
  await page.goto('/login');
  await login(page, 'a@jwt.com');
  await page.getByRole('link', { name: 'Admin', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Unable to load users');
  state.listFails = false;
  await page.getByRole('button', { name: 'Retry users' }).click();
  await page.getByRole('row').filter({ hasText: 'Mama Ricci' }).getByRole('button', { name: 'Delete' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Login', exact: true })).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('token'))).toBeNull();
});
